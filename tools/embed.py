#!/usr/bin/env python3
"""Embeds js/*.js into a C header as byte arrays: embed.py out.h file..."""
import os, sys

out, files = sys.argv[1], sys.argv[2:]
with open(out, "w") as f:
    f.write("// Generated by tools/embed.py. Do not edit.\n#pragma once\n#include <stddef.h>\n")
    for i, path in enumerate(files):
        data = open(path, "rb").read()
        f.write(f"static const char js_file_{i}[] = {{\n")
        for k in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[k:k + 24]) + ",\n")
        f.write("0};\n")
    f.write("static const struct { const char *name; const char *source; size_t length; } js_bundle[] = {\n")
    for i, path in enumerate(files):
        f.write(f'  {{"{os.path.basename(path)}", js_file_{i}, {os.path.getsize(path)}}},\n')
    f.write("};\n")
    f.write(f"static const int js_bundle_count = {len(files)};\n")
